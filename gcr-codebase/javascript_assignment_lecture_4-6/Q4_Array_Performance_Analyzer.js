// Q4. Array Performance Analyzer
// Generate eight random scores from 30 to 100 and summarize performance.

const scores = Array.from(
    { length: 8 },
    () => Math.floor(Math.random() * 71) + 30
);

const highestScore = Math.max(...scores);
const lowestScore = Math.min(...scores);
const totalScore = scores.reduce((sum, score) => sum + score, 0);
const averageScore = totalScore / scores.length;
const passedStudents = scores.filter(score => score >= 50).length;
const adjustedScores = scores.map(score => score); // Demonstrates map()

console.log(`Scores: ${adjustedScores.join(", ")}`);
console.log(`Highest score: ${highestScore}`);
console.log(`Lowest score: ${lowestScore}`);
console.log(`Average score: ${averageScore.toFixed(2)}`);
console.log(`Students passed (score >= 50): ${passedStudents}`);
